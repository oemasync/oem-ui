#!/usr/bin/env python3
"""Negative control for the consumer separator oracle.

The fleet gate (`probe-consumer-render.py`) decides whether a consumer's footer
or byline strands a separator at the end of a wrapped line. That oracle has to
be wrong in BOTH directions before it is worth anything:

  - it must NOT flag a correct row (a dot followed by text on one line)
  - it MUST flag a row whose line really ends with a separator, both when the
    separator is an ELEMENT and when it is generated by ::after - the "wrong
    fix" leaves no element behind, so an element-only probe cannot see it.

This fixture is that proof, kept in the repo so the oracle cannot quietly
regress to the version that failed on oem-portfolio: measured there, the footer
row is `<span class="cm-footer__dot">●</span> deployed from a private repo`, and
an element-only walk reported "1 line ending in a separator" at 390, 320 and
1280, in both themes, on a page whose dot sits at x=20..27.2 with the text
following at 39.4..241 on the same line.

usage: python3 tests/negctl-consumer-separators.py
exits 1 if the oracle is wrong in either direction.
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

_bp = os.environ.get("PLAYWRIGHT_BROWSERS_PATH")
if _bp and not os.path.isdir(_bp):
    del os.environ["PLAYWRIGHT_BROWSERS_PATH"]

from playwright.sync_api import sync_playwright  # noqa: E402

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("probe", HERE / "probe-consumer-render.py")
probe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(probe)

FIXTURE = """<!doctype html>
<html><head><meta charset="utf-8"><style>
  body { font: 400 15px/1.5 system-ui, sans-serif; margin: 0; padding: 20px; }
  .cm-footer__meta, .cm-footer__status { inline-size: 190px; }
  /* Case 3's defect: the dot hangs off the PRECEDING fragment. Nothing in the
     DOM is a separator, which is exactly why an element walk misses it. */
  .case-after .frag::after { content: "\\00b7"; margin-inline-start: 6px; opacity: .6; }
  /* The SHIPPED fix: one generated dot per fragment, attached to the item it
     precedes. A wrapped line may therefore START with a dot - declared, not a
     bug. */
  .case-before .frag + .frag::before { content: "\\00b7"; margin-inline-end: 6px; opacity: .6; }
</style></head><body>

  <!-- 1. the oem-portfolio shape: one element child (the dot), then a text node -->
  <div class="cm-footer__status" id="dot-then-text"><span class="cm-footer__dot">\u25cf</span> deployed from a private repo</div>

  <!-- 2. a dot that really is the last thing on the line -->
  <div class="cm-footer__meta" id="dot-last"><span>a self-healing watchdog</span><span class="cm-footer__dot">\u00b7</span></div>

  <!-- 3. the WRONG fix: generated ::after dots on a row that wraps. The fragments
       must be DIRECT children - a nested wrapper is one element to the oracle. -->
  <div class="cm-footer__meta case-after" id="after-dot"><span class="frag">alpha bravo charlie delta</span> <span class="frag">echo foxtrot golf hotel</span></div>

  <!-- 4. the SHIPPED fix: generated ::before dots; lines may START with one -->
  <div class="cm-footer__meta case-before" id="before-dot"><span class="frag">alpha bravo charlie delta</span> <span class="frag">echo foxtrot golf hotel</span></div>

</body></html>
"""

# id -> (expected endsWithSep, expected startsWithSep or None for "don't care")
EXPECT = {
    "cm-footer__status": (0, None),   # case 1 - the false positive
    "cm-footer__meta": (2, None),     # cases 2 and 3 - both must be flagged
}


def main():
    tmp = tempfile.mkdtemp(prefix="sepctl-")
    (Path(tmp) / "index.html").write_text(FIXTURE)
    port = 4523
    srv = subprocess.Popen(
        [sys.executable, "-m", "http.server", str(port), "--bind", "127.0.0.1", "--directory", tmp],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1.0)
    failures = []
    try:
        with sync_playwright() as p:
            browser = p.webkit.launch()
            ctx = browser.new_context(viewport={"width": 390, "height": 844},
                                      device_scale_factor=2, reduced_motion="reduce",
                                      has_touch=True)
            pg = ctx.new_page()
            pg.goto(f"http://127.0.0.1:{port}/", wait_until="load")
            pg.wait_for_timeout(200)
            rows = pg.evaluate(probe.MEASURE)["separatorRows"]
            browser.close()
    finally:
        srv.terminate()
        srv.wait(timeout=5)

    print(json.dumps(rows, indent=2))
    # Index-mapped, in document order, and COUNTED: an assertion keyed on a class
    # name silently skipped the two generated-separator cases and reported OK -
    # a control that can pass by not running is the same defect it polices.
    if len(rows) != 4:
        print(f"\nFAIL  expected 4 measured rows, got {len(rows)}")
        sys.exit(1)
    dot_then_text, dot_last, after_dot, before_dot = rows
    if dot_then_text["endsWithSep"] != 0:
        failures.append(f"false POSITIVE on a correct dot-then-text row: endsWithSep={dot_then_text['endsWithSep']}")
    if dot_last["endsWithSep"] != 1:
        failures.append(f"MISSED a trailing dot element: endsWithSep={dot_last['endsWithSep']}")
    if after_dot["lines"] < 2:
        failures.append(f"fixture did not wrap the ::after row ({after_dot['lines']} line) - the case proves nothing")
    if after_dot["endsWithSep"] < 1:
        failures.append(f"MISSED the ::after dot at a line end: endsWithSep={after_dot['endsWithSep']}")
    if before_dot["lines"] < 2:
        failures.append(f"fixture did not wrap the ::before row ({before_dot['lines']} line) - the case proves nothing")
    if before_dot["endsWithSep"] != 0:
        failures.append(f"false POSITIVE on the shipped ::before fix: endsWithSep={before_dot['endsWithSep']}")
    if before_dot["startsWithSep"] < 1:
        failures.append(f"the shipped ::before dot is not seen at a line start: startsWithSep={before_dot['startsWithSep']}")

    if failures:
        print("\nFAIL")
        for f in failures:
            print("  " + f)
        sys.exit(1)
    print("\nOK  dot-then-text passes; trailing element dot and generated ::after dot are both flagged")


if __name__ == "__main__":
    main()
