#!/usr/bin/env node
/**
 * mutation: the project-card wrapper
 *
 * Every assertion added this cycle is a guess until it has been made to
 * fail. This harness breaks the exact thing each check guards, runs the
 * suite, and reports which check fired.
 *
 * A pattern that no longer matches the source is a NO-OP - a failure of
 * THIS file, never a pass. The count reported in the cycle note must have
 * zero in it, or the harness itself is broken and the number is worthless.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (f) => join(root, f);
const COMP = 'src/astro/Project.astro';
const SHOW = 'src/pages/[...family].astro';

const MUTATIONS = [
	{
		// The prop binding. Hardcoding the target means every card on every
		// consumer points at the same place - the component stops being a
		// component.
		name: 'the link target is hardcoded instead of bound to href',
		file: COMP,
		from: /href=\{href\}/,
		to: 'href="#projects"',
		expectFail: 'does not bind the link target to the href prop',
	},
	{
		// The conditional slot, period. Unconditional, a card with no period
		// still emits an empty span that claims its baseline slot.
		name: 'the period span renders unconditionally',
		file: COMP,
		from: /\{period && <span class="cm-project__period">\{period\}<\/span>\}/,
		to: '<span class="cm-project__period">{period}</span>',
		expectFail: 'renders the period unconditionally',
	},
	{
		// The conditional slot, note. Unconditional, every card ships a dashed
		// rule with nothing under it.
		name: 'the note span renders unconditionally',
		file: COMP,
		from: /\{note && <span class="cm-project__note">\{note\}<\/span>\}/,
		to: '<span class="cm-project__note">{note}</span>',
		expectFail: 'renders the note unconditionally',
	},
	{
		// The a11y half of the reserved slot. aria-hidden is what keeps the
		// placeholder out of the assistive tree - without it a reader is told
		// there is a project that has no name and no link.
		name: 'the reserved slot loses its aria-hidden',
		file: COMP,
		from: /cm-project--pending" aria-hidden="true"/,
		to: 'cm-project--pending"',
		expectFail: 'the reserved slot must be a <div> hidden from assistive tech',
	},
	{
		// The structural half of the reserved slot: it is a <div>, not an <a>.
		// A link here is a tab stop that goes nowhere - the focusable
		// placeholder the CSS comment says the card must not be.
		name: 'the reserved slot becomes a link',
		file: COMP,
		from: /<div class="cm-project cm-project--pending" aria-hidden="true">([\s\S]*?)<\/div>/,
		to: '<a class="cm-project cm-project--pending" href="#projects">$1</a>',
		expectFail: 'the reserved slot must not be a link',
	},
	{
		// The em dash safety. The blurb separator is generated by ::before, so
		// the component must pass a bare string. A literal prefix here means
		// every card reads "— — blurb". Both branches carry the span, so the
		// pattern is global.
		name: 'a literal em dash is prefixed to the blurb',
		file: COMP,
		from: /<span class="cm-project__blurb">\{blurb\}<\/span>/g,
		to: '<span class="cm-project__blurb">\u2014 {blurb}</span>',
		expectFail: 'the blurb must be a bare string prop; the leading em dash is CSS, not a literal',
	},
	{
		// The empty-stack gate. Ungated, a card with no stack emits a blank
		// bottom-pinned row claiming its padding and its margin-top: auto.
		name: 'the stack row renders when there is nothing to pin',
		file: COMP,
		from: /\{stack && stack\.length > 0 && \(/,
		to: '(',
		expectFail: 'renders an empty stack row when there is nothing to pin',
	},
	{
		// The presence trap, showcase side: the reserved-slot specimen is
		// removed, so the section still builds and the heading still reads,
		// but the wrapper is no longer shown in its pending shape.
		name: 'the reserved-slot specimen is removed from the cards section',
		file: SHOW,
		from: /\t*<Project pending blurb="slot 04" \/>/,
		to: '',
		expectFail: 'the reserved-slot specimen is missing from the cards section',
		skipBuild: true,
	},
];

const runSuite = () => {
	const r = spawnSync('node', [join(root, 'tests/run.mjs')], { encoding: 'utf8' });
	return r.stdout || '';
};
const runBuild = () => spawnSync('npx', ['astro', 'build'], { cwd: root, encoding: 'utf8' });

let caught = 0, missed = 0, noop = 0;
for (const mut of MUTATIONS) {
	const file = p(mut.file);
	const orig = readFileSync(file, 'utf8');
	const mutated = orig.replace(mut.from, mut.to);
	if (mutated === orig) {
		noop++;
		console.log(`NO-OP  ${mut.name}\n       pattern did not match ${mut.file} - FIX THE HARNESS`);
		continue;
	}
	writeFileSync(file, mutated);
	try {
		if (!mut.skipBuild) {
			const b = runBuild();
			if (b.status !== 0) {
				console.log(`BUILD  ${mut.name}\n       the build itself failed: ${(b.stderr || '').split('\n').slice(0, 2).join(' ')}`);
			}
		}
		const out = runSuite();
		if (out.includes(mut.expectFail) && /FAIL/.test(out)) {
			caught++;
			console.log(`caught ${mut.name}\n       -> ${mut.expectFail}`);
		} else {
			missed++;
			console.log(`MISSED ${mut.name}\n       expected: ${mut.expectFail}`);
		}
	} finally {
		writeFileSync(file, orig);
	}
}
console.log(`\n${MUTATIONS.length} mutations: ${caught} caught, ${missed} missed, ${noop} no-op`);
if (noop) process.exit(2);
process.exit(missed ? 1 : 0);
